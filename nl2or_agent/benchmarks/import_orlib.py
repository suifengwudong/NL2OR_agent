"""Import real location instances from OR-Library (Beasley) into NL2OR benchmark cases.

Currently supports the p-median instances ``pmed1..pmed40``
(https://people.brunel.ac.uk/~mastjjb/jeb/orlib/pmedinfo.html).

For each requested instance we:
  1. download the graph (nodes, weighted edges, p)
  2. compute all-pairs shortest paths (scipy)
  3. solve the p-median MIP with PuLP/CBC to obtain a verified optimal objective
  4. emit a benchmark case into ``benchmarks/orlib_cases/``

Usage:
  uv run python benchmarks/import_orlib.py                 # pmed1..pmed10
  uv run python benchmarks/import_orlib.py --ids 1 5 10
  uv run python benchmarks/import_orlib.py --all           # pmed1..pmed40
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pulp
from scipy.sparse.csgraph import shortest_path

OUT_DIR = Path(__file__).parent / "orlib_cases"
SOLVERS_DIR = Path(__file__).parent / "references" / "solvers"
URL_FMT = "https://people.brunel.ac.uk/~mastjjb/jeb/orlib/files/pmed{id}.txt"


def render_solver_script(n: int, p: int, edges: list[tuple[int, int, int]]) -> str:
    """Self-contained solver script (shortest paths + p-median MIP → objective)."""
    edge_literal = ",\n    ".join(f"({i}, {j}, {w})" for i, j, w in edges)
    return f'''"""Reference solver: OR-Library pmed instance (n={n}, p={p}). Generated by import_orlib.py."""

import numpy as np
import pulp
from scipy.sparse.csgraph import shortest_path

N, P = {n}, {p}
EDGES = [
    {edge_literal},
]

INF = 10**9
D = np.full((N, N), INF, dtype=float)
for i, j, w in EDGES:
    D[i, j] = D[j, i] = w
SP = shortest_path(D, method="D")

prob = pulp.LpProblem("p_median", pulp.LpMinimize)
y = pulp.LpVariable.dicts("y", range(N), cat=pulp.LpBinary)
x = pulp.LpVariable.dicts("x", (range(N), range(N)), cat=pulp.LpBinary)
prob += pulp.lpSum(SP[i][j] * x[i][j] for i in range(N) for j in range(N))
for i in range(N):
    prob += pulp.lpSum(x[i][j] for j in range(N)) == 1
for i in range(N):
    for j in range(N):
        prob += x[i][j] <= y[j]
prob += pulp.lpSum(y[j] for j in range(N)) == P
prob.solve(pulp.PULP_CBC_CMD(msg=False))
value = pulp.value(prob.objective)
print("Objective:", round(value) if isinstance(value, (int, float)) else 0)
'''


def load_pmed(instance_id: int) -> tuple[int, int, np.ndarray, list[tuple[int, int, int]]]:
    import urllib.request

    with urllib.request.urlopen(URL_FMT.format(id=instance_id), timeout=30) as resp:
        tokens = resp.read().decode().split()
    n, m, p = int(tokens[0]), int(tokens[1]), int(tokens[2])
    vals = list(map(int, tokens[3 : 3 + 3 * m]))
    edges = [(vals[3 * i] - 1, vals[3 * i + 1] - 1, vals[3 * i + 2]) for i in range(m)]

    inf = 10**9
    dist = np.full((n, n), inf, dtype=float)
    for i, j, w in edges:
        dist[i, j] = dist[j, i] = w
    shortest = shortest_path(dist, method="D")
    return n, p, shortest, edges


def solve_p_median(n: int, p: int, shortest: np.ndarray) -> float:
    prob = pulp.LpProblem("p_median", pulp.LpMinimize)
    y = pulp.LpVariable.dicts("y", range(n), cat=pulp.LpBinary)
    x = pulp.LpVariable.dicts("x", (range(n), range(n)), cat=pulp.LpBinary)
    prob += pulp.lpSum(shortest[i][j] * x[i][j] for i in range(n) for j in range(n))
    for i in range(n):
        prob += pulp.lpSum(x[i][j] for j in range(n)) == 1
    for i in range(n):
        for j in range(n):
            prob += x[i][j] <= y[j]
    prob += pulp.lpSum(y[j] for j in range(n)) == p
    prob.solve(pulp.PULP_CBC_CMD(msg=False))
    value = pulp.value(prob.objective)
    return round(value) if isinstance(value, (int, float)) else 0.0


def render_problem(n: int, p: int, edges: list[tuple[int, int, int]]) -> str:
    lines = [
        f"在一个无向有权图中，有 {n} 个节点（编号 1~{n}）。",
        f"现需选择 {p} 个节点作为中位节点，使所有节点到其最近中位节点的最短路径距离之和最小。",
        "图中每条边为 (节点i, 节点j, 权重w)，边列表如下：",
    ]
    lines.append(", ".join(f"{i + 1} {j + 1} {w}" for i, j, w in edges))
    return "\n".join(lines)


def build_case(instance_id: int) -> dict:
    n, p, shortest, edges = load_pmed(instance_id)
    objective = solve_p_median(n, p, shortest)

    return {
        "id": f"pmed_{instance_id}",
        "name": f"OR-Library p-median pmed{instance_id}",
        "source": "OR-Library (Beasley) p-median; optimal verified by PuLP/CBC",
        "problem": render_problem(n, p, edges),
        "input_ir": {
            "problem_families": [{"id": "p_median", "confidence": 0.95}],
            "parameters": {"p": p},
            "constraint_blocks": [
                {"block_id": "assignment", "parameters": {}, "status": "required"},
                {"block_id": "linking", "parameters": {}, "status": "required"},
                {"block_id": "cardinality", "parameters": {"p": p}, "status": "required"},
            ],
            "objective": "minimize_total_weighted_distance",
        },
        "expected": {
            "families": ["p_median"],
            "block_ids": [
                "assign_each_demand_once",
                "link_assignment_to_open",
                "cardinality_open_p_facilities",
            ],
            "objective_block": "weighted_service_distance_objective",
        },
        "solver_objective": objective,
        "instance": {"n": n, "p": p, "edges": len(edges), "shortest_path_sum": objective},
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Import OR-Library p-median benchmark cases")
    parser.add_argument("--ids", nargs="+", type=int, help="specific pmed ids, e.g. 1 2 5")
    parser.add_argument("--all", action="store_true", help="import pmed1..pmed40")
    args = parser.parse_args()

    if args.all:
        ids = list(range(1, 41))
    elif args.ids:
        ids = args.ids
    else:
        # pmed1..pmed5 are n=100 (CBC solves in ~1s).  Larger ids are n=200+
        # and take minutes with CBC — pass explicit --ids or --all if needed.
        ids = list(range(1, 6))

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    SOLVERS_DIR.mkdir(parents=True, exist_ok=True)
    for iid in ids:
        case = build_case(iid)
        path = OUT_DIR / f"{case['id']}.json"
        with open(path, "w", encoding="utf-8") as f:
            json.dump(case, f, ensure_ascii=False, indent=2)

        n, p, _shortest, edges = load_pmed(iid)
        solver_path = SOLVERS_DIR / f"{case['id']}.py"
        with open(solver_path, "w", encoding="utf-8") as f:
            f.write(render_solver_script(n, p, edges))

        print(f"imported {case['id']}: objective={case['solver_objective']}")

    print(f"\nDone: {len(ids)} cases written to {OUT_DIR}")


if __name__ == "__main__":
    main()
